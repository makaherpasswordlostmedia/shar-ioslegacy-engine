#!/usr/bin/env python3
"""№430: compact PS2 arrest reference for tests/hnr/arrest_ps2.c from the 7 PS2 arrest records.

Source (read only): build/ps2ref/answers/<rec>/trace.tsv of the main tree (knowledge/twins_library/разбор/ps2ref.md, section 1:
b3_bust, b3_bust80, b3_fine30, b3_fine200, b3_coinauth, b3_coins30, b3_coins80). Column `coins` of these recipes is 0x9e79c0
(coin display stage, NOT coins) and is never read here. Per sample: rel (PAL 50 Hz frames), chase flags 0x6121b4, bust_near_ms
0x6121dc, bust_ms 0x6121ec, player car position mat[12]/mat[14] and velocity car_vel[0]/[2], police 0xa257e0 position.
b3_bust stores raw f32 bits in its m61xxxx columns; they are decoded. Writes tests/hnr/arrest_ps2_ref.h.
Usage: python3 -I tests/hnr/arrest_ps2_ref.py [ANSWERS_DIR]
"""
import csv, hashlib, math, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / 'Downloads/shar-psp/build/ps2ref/answers'
RECS = ['b3_bust', 'b3_bust80', 'b3_fine30', 'b3_fine200', 'b3_coinauth', 'b3_coins30', 'b3_coins80']


def num(v):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return float('nan')
    if x > 1e6 and x == int(x):  # raw u32 bits of an f32 (b3_bust m61xxxx columns)
        return struct.unpack('<f', struct.pack('<I', int(x)))[0]
    return x


out = ['// generated by tests/hnr/arrest_ps2_ref.py from the PS2 arrest records (build/ps2ref/answers/*/trace.tsv), do not edit',
       '// sample: rel (PAL 50 Hz frame), police present (0x6121b4 & 1), d (m, x/z player car to police), v (km/h, player car x/z),',
       '// ps2 near counter 0x6121dc (ms), ps2 bust timer 0x6121ec (ms)',
       'typedef struct { int rel, police; float d, kmh, near, bust; } ArrestSample;',
       'typedef struct { const char *name, *sha256; int chase, police, n; const ArrestSample *s; } ArrestRec;']
table = []
for r in RECS:
    p = ANS / r / 'trace.tsv'
    sha = hashlib.sha256(p.read_bytes()).hexdigest()
    rows = list(csv.DictReader(p.open(), delimiter='\t'))
    chase = police = None; samples = []; ended = False
    for row in rows:
        g = lambda k, a=None: num(row[k] if k in row else row.get(a))
        rel = int(float(row['rel'])); ch = int(g('chase', 'm6121b4'))
        if chase is None and ch & 0x100: chase = rel
        if chase is None: continue
        if police is None and ch & 1: police = rel
        if police is None: continue
        near, bust = g('bust_near_ms', 'm6121dc'), g('bust_ms', 'm6121ec')
        d = math.hypot(g('mat[12]') - g('pol_x'), g('mat[14]') - g('pol_z'))
        v = math.hypot(g('car_vel[0]'), g('car_vel[2]')) * 3.6
        samples.append((rel, ch & 1, d, v, near, bust))
        if any(s[5] > 0 for s in samples) and bust <= 0: ended = True; break
    if not ended: sys.exit(f'{r}: arrest timer never ended')
    name = 'S_' + r
    out.append(f'static const ArrestSample {name}[] = {{')
    out += [f'  {{{s[0]}, {s[1]}, {s[2]:.3f}f, {s[3]:.2f}f, {s[4]:.0f}, {s[5]:.0f}}},' for s in samples]
    out.append('};')
    table.append(f'  {{"{r}", "{sha}", {chase}, {police}, {len(samples)}, {name}}},')
out.append('static const ArrestRec ARREST_RECS[] = {'); out += table; out.append('};')
(ROOT / 'tests/hnr/arrest_ps2_ref.h').write_text('\n'.join(out) + '\n')
print(f'wrote tests/hnr/arrest_ps2_ref.h: {len(table)} records')
