#!/bin/bash
# Гейт правок 164/164б/187/388 (удар как у оригинала): машина порта брошена с тем же состоянием, что бот близнеца в своём PCSX2
# (knowledge/facts/ps2-jumps-walls.yaml, build/twins/o4/v22_*), должна встать там же, где оригинал: J11-9 (бок цистерны), F12-6
# левые перила (башня), F12-6 правые перила (шов ящиков 69/70) — конец ближе 1,2 м по x/z к точке оригинала.
# F12-6R (правка 164б, 03.10): точка оригинала — где он встал у шва (v22_f126r кадр 7650: −113,05; 463,31 в осях порта); дальше
# оригинал за 3 с заваливается на бок (~60°) и сползает на 1,2 м вперёд и 0,3 м вбок — этого порт не делает, стоит у шва ровно.
# Состояние броска (388/377, 08.10, attempt55/f12): близнец пишет car_cm (центр масс) и car_vel, курс кузова остаётся каким был
# (jump.py --place). Высота: car_cm.y → начало порта (низ колёс) = car_cm.y − 0,667 (comBase famil_v; центр масс PS2 над землёй 0,66,
# tools/twins/placement.py CM_LIFT) — раньше бросали на 0,67 м выше. Курс кузова: ψ из jump.tsv (atan2 носа в осях игры), порт h = 180° − ψ
# (z зеркален): J11-9 ψ 0,0 → 180; F12-6L ψ −160,2 → −19,8; F12-6R ψ 172,6 → 7,4 — раньше бросали вдоль скорости. Скорость — по осям
# (AW_VHEAD, курс скорости): F12 (0; −1; −18); J11-9 (0; 0; 22) по карточке, но спуск оригинала (кадры 3758–3786) даёт vy0 = −1,0 м/с при
# g 16 (Δy/t = 1,0 + 8,0·t) — берём −1. Конец: начало модели порта (низ колёс + подъём модели по оси вверх кузова), как в трассе оригинала.
# Красные: -DCAR_CRASH_V=1e9f (удар упругий, как до правки 187) и -DCAR_BELLY_EDGES=0 (днище без рёбер узких балок, как до
# правки 388: F12-6L ползёт по балке назад) — оба обязаны упасть. Контроль киля (-DCAR_BELLY_KEEL=0, правка 164б) снят 08.10: на
# состоянии близнеца он не различим — без рёбер F12-6R мимо (17 м) и с килем, и без; с рёбрами балки держат и без киля (немая проверка).
# Известное расхождение (по слову Роба 08.10 22:4x — точечное исключение, чтобы закрыть наряд): F12-6R — порт проходит балку, но у
# шва 69/70 не встаёт носом, как оригинал (нужен его клевок, В98), допуск 6,0 м вместо 1,2 — пока не хуже измеренного 5,2.
#   tests/airwalls/crash.sh [LEVEL]   -> PASS/FAIL, build/airwalls/crash_*.txt
set -u
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"; cd "$ROOT"; OUT="${OUT_DIR:-build/airwalls}"; mkdir -p "$OUT"
LEVEL="${1:-build/level.shr}"
build() { cc -std=c11 -O2 -Wall -Wno-unused-function -DSKIN_HOST ${EXTRA_CFLAGS:-} "$@" -I viewer tests/airwalls/host.c "${CAR_C:-viewer/car.c}" "${COL_C:-viewer/col.c}" \
  viewer/props.c viewer/stateprops.c viewer/coins.c -lm -o "$OUT/crash_bin" || exit 2; }
# место | бросок (порт: x y z курс° вперёд вниз сек) | курс скорости° | конец оригинала x z (порт)
# место | бросок | курс скорости° | конец оригинала x z (порт) | допуск м (пусто = 1,2; иначе известное расхождение)
CASES="J11-9|172 5.333 404 180 22 1 1.6|180|172.44 388.04|
F12-6L|-124.9 8.235 452 -19.8 18 1 2|0|-125.33 452.84|
F12-6R|-114 8.235 452 7.4 18 1 2|0|-113.05 463.31|6.0"
run() {
  bad=0
  while IFS='|' read -r nm args vh orig tol; do
    end=$(AW_VHEAD="$vh" "$OUT/crash_bin" "$LEVEL" drop $args 0 | tail -1)
    read -r ex ez <<< "$(echo "$end" | awk '{print $3, $5}')"; read -r ox oz <<< "$orig"
    d=$(awk -v a="$ex" -v b="$ez" -v c="$ox" -v e="$oz" 'BEGIN{printf "%.2f", sqrt((a-c)^2+(b-e)^2)}')
    ok=$(awk -v d="$d" -v t="${tol:-1.2}" 'BEGIN{print (d <= t) ? 1 : 0}')
    echo "$nm: порт ($ex, $ez), оригинал ($ox, $oz), $d м $( [ "$ok" = 1 ] && { [ -n "$tol" ] && echo "OK (известное расхождение, допуск $tol)" || echo OK; } || echo МИМО)"
    [ "$ok" = 1 ] || bad=$((bad + 1))
  done <<< "$CASES"
  return $bad
}
build -DCAR_CRASH_V=1e9f; run > "$OUT/crash_red.txt"; rb=$?
build -DCAR_BELLY_EDGES=0 -DCAR_TYRE_LEVER_OLD=1 -DCAR_WEEBLE_GROUND_OLD=1; run > "$OUT/crash_red_edges.txt"; re=$?;   # №406: F12-6L держит и плечо шин — красный = днище без рёбер на коде до 406
 grep -q "^F12-6L:.*МИМО" "$OUT/crash_red_edges.txt" || re=0
build; run > "$OUT/crash_green.txt"; gb=$?
cat "$OUT/crash_green.txt"
[ $rb -gt 0 ] && echo "красный (удар упругий): мимо $rb из 3 — упал, как должен" || echo "КРАСНЫЙ НЕ ПОЙМАН (удар упругий)"
[ $re -gt 0 ] && echo "красный (днище без рёбер балок): F12-6L $(grep '^F12-6L' "$OUT/crash_red_edges.txt" | sed 's/^F12-6L: //') — упал, как должен" \
  || echo "КРАСНЫЙ НЕ ПОЙМАН (днище без рёбер балок)"
[ $rb -gt 0 ] && [ $re -gt 0 ] && [ $gb -eq 0 ] && { echo PASS; exit 0; } || { echo FAIL; exit 1; }
