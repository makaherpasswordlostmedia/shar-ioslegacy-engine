// ним (карта высот, ground()), с гистерезисом и выдержкой: включается с FAR909_ON м, гаснет не раньше чем через FAR909_HOLD с и ниже FAR909_OFF м. FAR909_OLD=1 — прежнее правило (глаз выше ячейки ленты на FAR150_UP).
// Чистая функция без PSP-заголовков: её же гоняет tests/horizon/far909.sh по трассе проезда
#pragma once
#ifndef FAR909_OLD
#define FAR909_OLD 0
#endif
#ifndef FAR909_ON
#define FAR909_ON 12.f   // м над землёй под глазом: с этого «высокий взгляд» (даль 250 м)
#endif
#ifndef FAR909_OFF
#define FAR909_OFF 8.f   // м: ниже — «высокий взгляд» гаснет (после выдержки)
#endif
#ifndef FAR909_HOLD
#define FAR909_HOLD 1.f   // с: меньше не гасить — прыжок/съезд дрожит у порога
#endif
typedef struct { int hi; float t; } Far909;
// clr — высота глаза над землёй под ним, м (< -1e8 — земли под глазом нет: тогда решает прежнее правило old, 1 — выше ячейки ленты на FAR150_UP); dt — с. Возвращает 1, если нужна полная даль
static int far909Step(Far909 *s, float clr, int old, float dt) {
  if (FAR909_OLD) return s->hi = old;
  int hi = clr < -1e8f ? old : (s->hi ? (clr >= FAR909_OFF) : (clr >= FAR909_ON));
  if (hi) { s->hi = 1; s->t = 0.f; return 1; }
  if (s->hi && (s->t += dt) < FAR909_HOLD) return 1;
  s->hi = 0; s->t = 0.f; return 0;
}
