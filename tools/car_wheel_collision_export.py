#!/usr/bin/env python3
"""Export four authored tyre collision spheres, without converting/rendering assets.

The source mesh radius is not necessarily the collision radius. Slot ordering
comes from the original wheel joint position, not the w0..w3 suffix.
Centres are in the port's body axes, relative to the rendered model origin.
The offset from the wheel joint pivot is exported separately: steering and
wheel spin rotate it about the pivot (up to 1.7 cm on authored data).
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT/'tools'), str(ROOT/'hit-and-run-web/tools')]
from car_dump import skeleton
from car_inertia_export import collision_shapes
from p3d import read, string


def wheels(path):
    root = read(path)
    comp = next(c for c in root.children if c.id==0x4512)
    _, offset = string(comp.data)
    name, _ = string(comp.data, offset)
    joints = skeleton(next(c for c in root.children if c.id==0x4500 and string(c.data)[0]==name))
    result = [None]*4
    for shape in collision_shapes(root, joints):
        if shape['joint_name'] not in ('w0','w1','w2','w3'):
            continue
        if shape['kind']!='sphere' or shape['radius']<=0:
            raise ValueError(f'{path.name}: wheel is not a positive sphere')
        pivot = joints[shape['joint']][3][3,:3]
        slot = (0 if pivot[2]>0 else 2)+(1 if pivot[0]>0 else 0)
        if result[slot] is not None:
            raise ValueError(f'{path.name}: duplicate wheel slot {slot}')
        shape['offset'] = (np.array(shape['center'])-pivot*[-1.,1.,1.]).tolist()
        result[slot] = shape
    if any(item is None for item in result):
        raise ValueError(f'{path.name}: missing wheel slot')
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--report', type=Path, required=True)
    args = ap.parse_args()
    game = ROOT/'hit-and-run-web/source/game'
    rows = {}
    for con in sorted((game/'scripts/cars').glob('*.con')):
        path = game/'art/cars'/f'{con.stem}.p3d'
        if path.is_file():
            rows[con.stem] = dict(wheels=wheels(path), source_sha256=hashlib.sha256(path.read_bytes()).hexdigest())
    def number(value):
        text = f'{value:.9g}'
        return text+('f' if '.' in text or 'e' in text else '.0f')
    lines = ['// Generated by tools/car_wheel_collision_export.py; original collision spheres, not mesh bounds',
             '#ifndef CAR_WHEEL_COLLISION_H', '#define CAR_WHEEL_COLLISION_H',
             'typedef struct { const char *name; float sphere[4][4], offset[4][3]; } CarWheelCollision;',
             'static const CarWheelCollision carWheelCollision[] = {']
    for name, row in rows.items():
        values = ['{'+', '.join(map(number, shape['center']+[shape['radius']]))+'}' for shape in row['wheels']]
        offsets = ['{'+', '.join(map(number, shape['offset']))+'}' for shape in row['wheels']]
        lines.append('  {"'+name+'", {'+', '.join(values)+'}, {'+', '.join(offsets)+'}},')
    lines += ['};', '#endif', '']
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text('\n'.join(lines))
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(rows, indent=2)+'\n')
    print(f'Exported {len(rows)} cars / {4*len(rows)} native tyre collision spheres')


if __name__=='__main__':
    main()
